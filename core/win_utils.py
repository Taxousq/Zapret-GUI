"""Вспомогательные средства для запуска внешних команд.

Здесь живёт единственная константа — :data:`CREATE_NO_WINDOW`. Она передаётся
в ``creationflags`` каждого запуска консольной команды (``sc``, ``net``, ``reg``,
``taskkill``, ``wevtutil``, ``powershell``, ``cmd``): без этого флага Windows
создаёт для дочернего процесса собственную консоль, и на экране на долю
секунды появляется чёрное окно. Заметнее всего это на опросе статуса службы
(``poll_status`` раз в 5 секунд) и на командах разделов «Логи» и «Тестер».

На Linux/macOS константы ``subprocess.CREATE_NO_WINDOW`` не существует,
поэтому там значение равно 0: ``creationflags=0`` означает «без дополнительных
флагов», и код остаётся кроссплатформенным.
"""

from __future__ import annotations

import subprocess

#: Скрывает консольное окно дочернего процесса (флаг существует только на Windows).
CREATE_NO_WINDOW: int = getattr(subprocess, "CREATE_NO_WINDOW", 0)

__all__ = ["CREATE_NO_WINDOW"]
